// Builds docs/preview.html from docs/preview.template.html by inlining the game
// from app/src/main/assets/game/. The game has one source; this page and the
// Android app both run it.
//
//   node docs/build-preview.mjs                 -> docs/preview.html (standalone)
//   node docs/build-preview.mjs --artifact out  -> also writes the page body only,
//                                                  the form a Claude artifact publishes
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const gameDir = join(here, '..', 'app', 'src', 'main', 'assets', 'game');

export function buildPreview(artifactPath) {
  const template = readFileSync(join(here, 'preview.template.html'), 'utf8');
  const parts = { '/*@GAME_CSS@*/': 'game.css', '/*@GAME_JS@*/': 'game.js' };
  let body = template;
  for (const [marker, file] of Object.entries(parts)) {
    if (body.split(marker).length !== 2) throw new Error(`template must contain ${marker} exactly once`);
    body = body.split(marker).join(readFileSync(join(gameDir, file), 'utf8'));
  }
  const page = [
    '<!doctype html>',
    '<html lang="ko">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    '<!-- Generated by docs/build-preview.mjs. Edit docs/preview.template.html or the game in app/src/main/assets/game/. -->',
    '</head>',
    '<body>',
    body,
    '</body>',
    '</html>',
    '',
  ].join('\n');
  writeFileSync(join(here, 'preview.html'), page);
  if (artifactPath) writeFileSync(artifactPath, body);
  return join(here, 'preview.html');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--artifact');
  const out = buildPreview(i > 0 ? process.argv[i + 1] : undefined);
  console.log(`wrote ${out}`);
}
